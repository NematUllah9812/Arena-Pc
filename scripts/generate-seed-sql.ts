/**
 * Generates supabase/seed.sql from the typed seed modules so the in-memory
 * fallback and the live Supabase catalogue are always byte-for-byte aligned.
 *
 *   npx tsx scripts/generate-seed-sql.ts
 *
 * Timestamps are emitted relative to a fixed epoch and shifted by
 * (NOW() - epoch) at apply time, so flash-deal windows and Build Bay logs
 * are always "live" no matter when the seed runs. Idempotent: re-running
 * never duplicates rows (ON CONFLICT DO NOTHING).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SEED_PRODUCTS } from '../src/lib/data/seed-catalog';
import { SEED_PACKAGES, materializeDeals } from '../src/lib/data/seed-commerce';
import { buildSeedOrders } from '../src/lib/data/build-seed-orders';

const EPOCH = Date.parse('2026-01-01T12:00:00.000Z');
const TAG = '$vortex_seed$';

function block(value: unknown): string {
  const json = JSON.stringify(value);
  if (json.includes(TAG)) throw new Error('Seed payload collides with dollar-quote tag');
  return `${TAG}${json}${TAG}::jsonb`;
}

const products = SEED_PRODUCTS.map((p) => ({ ...p, reserved_quantity: 0, created_at: undefined, updated_at: undefined }));
const deals = materializeDeals(EPOCH);
const { orders, logs } = buildSeedOrders(SEED_PRODUCTS, EPOCH);

const sql = `-- =====================================================================
-- VORTEX LABS — seed data (generated by scripts/generate-seed-sql.ts)
-- ${products.length} SKUs · ${SEED_PACKAGES.length} Syndicate Packages · ${deals.length} flash deals · ${orders.length} demo orders
-- DO NOT EDIT BY HAND.
-- =====================================================================

DO $seed$
DECLARE
  v_shift INTERVAL := NOW() - '${new Date(EPOCH).toISOString()}'::timestamptz;
BEGIN
  -- Products ------------------------------------------------------------
  INSERT INTO public.products (
    id, sku, name, slug, brand, category, base_price_cents, sale_price_cents, cost_price_cents,
    stock_quantity, reserved_quantity, warehouse_bin, days_in_inventory, overstock_priority,
    is_leftover_clearance, is_active, weight_grams, performance_score, gaming_tier_weight,
    workstation_tier_weight, tdp_watts, primary_image_url, gallery_urls, model_3d_glb_url, specs, description
  )
  SELECT
    r.id, r.sku, r.name, r.slug, r.brand, r.category, r.base_price_cents, r.sale_price_cents, r.cost_price_cents,
    r.stock_quantity, 0, r.warehouse_bin, r.days_in_inventory, r.overstock_priority,
    r.is_leftover_clearance, r.is_active, r.weight_grams, r.performance_score, r.gaming_tier_weight,
    r.workstation_tier_weight, r.tdp_watts, r.primary_image_url, COALESCE(r.gallery_urls, '{}'), r.model_3d_glb_url,
    COALESCE(r.specs, '{}'::jsonb), r.description
  FROM jsonb_populate_recordset(NULL::public.products, ${block(products)}) AS r
  ON CONFLICT (sku) DO NOTHING;

  -- Syndicate Packages ---------------------------------------------------
  INSERT INTO public.syndicate_packages (id, slug, name, tier, tagline, description, hero_accent_hex, component_skus, target_fps_note, is_active, sort_order)
  SELECT r.id, r.slug, r.name, r.tier, r.tagline, r.description, r.hero_accent_hex, r.component_skus, r.target_fps_note, r.is_active, r.sort_order
  FROM jsonb_populate_recordset(NULL::public.syndicate_packages, ${block(SEED_PACKAGES)}) AS r
  ON CONFLICT (slug) DO NOTHING;

  -- Flash deals (windows shifted to NOW) ------------------------------------
  INSERT INTO public.flash_deals (id, product_id, deal_title, deal_price_cents, max_claims, claimed_count, reserved_claims, starts_at, expires_at, banner_accent_hex, is_active)
  SELECT r.id, r.product_id, r.deal_title, r.deal_price_cents, r.max_claims, r.claimed_count, 0,
         r.starts_at + v_shift, r.expires_at + v_shift, r.banner_accent_hex, r.is_active
  FROM jsonb_populate_recordset(NULL::public.flash_deals, ${block(deals)}) AS r
  ON CONFLICT (id) DO NOTHING;

  -- Demo orders + Build Bay telemetry --------------------------------------
  INSERT INTO public.orders (
    id, order_number, customer_email, customer_name, shipping_address, fulfillment_type,
    includes_bios_preflash_service, includes_foam_gpu_brace, assembly_fee_cents, services_fee_cents,
    subtotal_cents, total_charged_cents, current_stage, assigned_technician_code, estimated_dispatch_date,
    carrier, carrier_tracking_number, manifest_snapshot, compatibility_confidence,
    requires_tech_clearance_check, syndicate_package_slug, created_at, updated_at
  )
  SELECT
    r.id, r.order_number, r.customer_email, r.customer_name, r.shipping_address, r.fulfillment_type,
    r.includes_bios_preflash_service, r.includes_foam_gpu_brace, r.assembly_fee_cents, r.services_fee_cents,
    r.subtotal_cents, r.total_charged_cents, r.current_stage, r.assigned_technician_code,
    (r.estimated_dispatch_date + v_shift)::date,
    r.carrier, r.carrier_tracking_number, r.manifest_snapshot, r.compatibility_confidence,
    r.requires_tech_clearance_check, r.syndicate_package_slug, r.created_at + v_shift, r.updated_at + v_shift
  FROM jsonb_populate_recordset(NULL::public.orders, ${block(orders)}) AS r
  ON CONFLICT (order_number) DO NOTHING;

  INSERT INTO public.build_bay_telemetry_logs (id, order_id, stage, technician_code, telemetry_metrics, proof_screenshot_url, technician_notes, logged_at)
  SELECT r.id, r.order_id, r.stage, r.technician_code, r.telemetry_metrics, r.proof_screenshot_url, r.technician_notes, r.logged_at + v_shift
  FROM jsonb_populate_recordset(NULL::public.build_bay_telemetry_logs, ${block(logs)}) AS r
  WHERE EXISTS (SELECT 1 FROM public.orders o WHERE o.id = r.order_id)
  ON CONFLICT (id) DO NOTHING;
END
$seed$;

REFRESH MATERIALIZED VIEW public.mv_hardware_facets;
`;

const out = join(process.cwd(), 'supabase', 'seed.sql');
writeFileSync(out, sql);
console.log(`seed.sql → ${out} (${(sql.length / 1024).toFixed(1)} KB; ${products.length} products, ${orders.length} orders, ${logs.length} logs)`);
